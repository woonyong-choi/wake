/** the words of a key, with its {name} places filled */
export const t = (key, vars) => {
  const s = ko[key];
  if (s == null) throw new Error(`sim locale: no key ${key}`);
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
};
