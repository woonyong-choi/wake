#!/usr/bin/env node
/*
 * Builds icon glyph files (glyph source: lucide-static icon-nodes.json, ISC License).
 *   kit:  node kit/tools/glyphs.mjs <icon-nodes.json>
 *         -> kit/icons/glyphs.js (only glyphs used by the kit base table BASE_MAP)
 *   app:  node kit/tools/glyphs.mjs <icon-nodes.json> --app <app icon map module> --out <app glyphs.js>
 *         -> glyphs used by the app table (ICON_MAP) that the kit lacks, as `export const GLYPHS = {...}`;
 *            the app's own drawings already in that file ({ viewBox, svg } entries, e.g. the brand mark) are kept as they are
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const nodesPath = args[0];
const opt = k => { const i = args.indexOf(k); return i > 0 ? args[i + 1] : null; };
if (!nodesPath) { console.error('usage: glyphs.mjs <icon-nodes.json> [--app <map module> --out <file>]'); process.exit(2); }
const nodes = JSON.parse(readFileSync(nodesPath, 'utf8'));
/* Filled variant: every shape merged into one path (circles become two arcs, rect corners stay square), drawn with fill-rule evenodd so inner shapes become holes */
function fillGlyph(inner) {
  const ds = [];
  for (const m of inner.matchAll(/<(path|circle|rect)\s([^>]*?)\/>/g)) {
    const a = Object.fromEntries([...m[2].matchAll(/([\w-]+)="([^"]*)"/g)].map(x => [x[1], x[2]]));
    if (m[1] === 'path') ds.push(a.d);
    else if (m[1] === 'circle') { const cx = +a.cx, cy = +a.cy, r = +a.r; ds.push(`M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`); }
    else ds.push(`M${+(a.x || 0)} ${+(a.y || 0)}h${a.width}v${a.height}h${-a.width}z`);
  }
  return `<path d="${ds.join('')}"/>`;
}
const svg0 = k => nodes[k].map(([tag, a]) => `<${tag} ${Object.entries(a).filter(([n]) => n !== 'key').map(([n, v]) => `${n}="${v}"`).join(' ')}/>`).join('');
/* A key ending in -fill is the filled variant of the key without the suffix */
const svg = k => (!nodes[k] && k.endsWith('-fill') && nodes[k.slice(0, -5)]) ? fillGlyph(svg0(k.slice(0, -5))) : svg0(k);
const write = (file, keys, head, own = {}) => {
  const lines = [head, 'export const GLYPHS = {'];
  for (const k of [...keys].sort()) {
    if (own[k]) { lines.push(`  '${k}': { viewBox: '${own[k].viewBox}', svg: '${own[k].svg}' },`); continue; }
    if (!nodes[k] && !(k.endsWith('-fill') && nodes[k.slice(0, -5)])) { console.error(`missing glyph: ${k}`); process.exit(1); }
    lines.push(`  '${k}': '${svg(k)}',`);
  }
  lines.push('};', '');
  writeFileSync(file, lines.join('\n'));
  console.log(`${file}: ${keys.size} glyphs`);
};
const { BASE_MAP } = await import(pathToFileURL(resolve(here, '../icons/base-map.js')));
const kitKeys = new Set(Object.values(BASE_MAP).map(v => v[0]));
const app = opt('--app');
if (!app) {
  write(resolve(here, '../icons/glyphs.js'), kitKeys, '/* Kit glyphs (viewBox 24, stroke). Source lucide 0.469.0, ISC License (https://lucide.dev/license).\n * Generated by kit/tools/glyphs.mjs. To switch to a licensed icon set, replace only this file and the app glyph file. */');
} else {
  const { ICON_MAP } = await import(pathToFileURL(resolve(app)));
  const keys = new Set(Object.values(ICON_MAP).map(v => v[0]).filter(k => !kitKeys.has(k)));
  const out = resolve(opt('--out'));
  const prev = existsSync(out) ? (await import(pathToFileURL(out))).GLYPHS : {};
  const own = Object.fromEntries(Object.entries(prev).filter(([, g]) => typeof g === 'object'));
  write(out, keys, '/* App glyphs (viewBox 24, stroke; own drawings { viewBox, svg } are filled). Source lucide 0.469.0, ISC License (https://lucide.dev/license).\n * Generated with kit/tools/glyphs.mjs --app; own drawings are kept. */', own);
}
